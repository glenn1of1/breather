write("report-receipt", C.ReportReceipt, { receiptId: "SEH-2026-11-0042", submittedAt: "2026-11-30T17:00:00.000Z" });

// ---------- static import map for API stubs (lib/fixtures.ts) ----------
const names = readdirSync(OUT).filter((f) => f.endsWith(".json")).map((f) => f.replace(/\.json$/, "")).sort();
writeFileSync(
  join(__dirname, "..", "lib", "fixtures.ts"),
  [
    "// GENERATED by scripts/make-fixtures.ts. Do not edit.",
    "// Fixtures for API stubs while the real implementation is being built. Static imports so they are",
    "// bundled on Vercel. Remove each use once its endpoint is real. Regenerate with: npm run fixtures",
    'import "server-only";',
    ...names.map((n, i) => `import f${i} from "@/fixtures/${n}.json";`),
    "",
    "const FIXTURES: Record<string, unknown> = {",
    ...names.map((n, i) => `  "${n}": f${i},`),
    "};",
    "",
    "export async function fixture(name: string): Promise<unknown> {",
    "  const data = FIXTURES[name];",
    "  if (data === undefined) throw new Error(`unknown fixture: ${name}`);",
    "  return structuredClone(data);",
    "}",
    "",
  ].join("\n"),
);
console.log("lib/fixtures.ts");
