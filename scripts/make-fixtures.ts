// Generates fixtures/*.json for frontend work before the real API exists.
// Every fixture is parsed with its contract before it is written. Run: npm run fixtures
import { mkdirSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import type { z } from "zod";
import * as C from "../lib/contracts";
import { buildSnapshots } from "../lib/aggregate/build-snapshots";
import { generateScenario } from "../lib/seed/generate";
import { costToContinue } from "../lib/engine/cost";
import { PREVIEW_START } from "../config/public";
import { previewEstimate } from "../lib/engine/preview";

const OUT = join(__dirname, "..", "fixtures");
mkdirSync(OUT, { recursive: true });

function write<T extends z.ZodTypeAny>(name: string, schema: T, data: z.input<T>) {
  const parsed = schema.parse(data);
  writeFileSync(join(OUT, `${name}.json`), JSON.stringify(parsed, null, 2) + "\n");
  console.log(`fixtures/${name}.json`);
}


// ---------- survey results ----------
write("survey.accepted", C.SurveyResult, { outcome: "accepted", claimNo: "PH-7K3Q-92" });
write("survey.waitlisted", C.SurveyResult, { outcome: "waitlisted", claimNo: "PH-M4XR-15" });
write("survey.pending", C.SurveyResult, { outcome: "pending", claimNo: "PH-2B9T-07", decidedOn: "2026-11-02" });
write("survey.not_eligible", C.SurveyResult, { outcome: "not_eligible" });

// ---------- dashboards ----------
// Generated by the real pipeline (seed → buildSnapshots), so fixtures match production exactly.
for (const sc of C.Scenario.options) {
  const snaps = buildSnapshots(generateScenario(sc));
  write(`dashboard.${sc}.week13`, C.DashboardSnapshot, snaps[12]!);
  if (sc === "scale") {
    write("dashboard.scale.week1", C.DashboardSnapshot, snaps[0]!);
    write("dashboard.scale.week2", C.DashboardSnapshot, snaps[1]!);
    write("dashboard.scale.week6", C.DashboardSnapshot, snaps[5]!);
  }
}

