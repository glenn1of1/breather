for (const sc of C.Scenario.options) write(`verdict.${sc}`, C.VerdictResult, verdicts[sc]);

// ---------- cost ----------
// Real engine, real observed inputs from the seeded pilot.
const weeklyHours = (snap: C.DashboardSnapshot) => snap.usage.weekly.map((w) => (C.isSuppressed(w.hours) ? null : w.hours));
const observed = (sc: C.Scenario) => {
  const snap = buildSnapshots(generateScenario(sc))[12]!;
  const ci = snap.pilotEnd!.costInputs;
  const num = (v: C.SuppressibleNumber, fallback: number) => (C.isSuppressed(v) ? fallback : v);
  return {
    snap,
    assumptions: {
      providerRate: 50,
      adminFeePct: 0.15,
      places: ci.places,
      uptake: num(ci.uptake, 0.6),
      hoursPerCaregiverPerMonth: num(ci.hoursPerCaregiverPerMonth.mean, 4),
      hoursLow: num(ci.hoursPerCaregiverPerMonth.p25, 3),
      hoursHigh: num(ci.hoursPerCaregiverPerMonth.p75, 5),
    },
  };
};
const sustainObs = observed("sustain");
const scaleObs = observed("scale");
write("cost.assumptions", C.CostAssumptions, sustainObs.assumptions);
write("cost.sustain", C.CostResult, costToContinue(sustainObs.assumptions, weeklyHours(sustainObs.snap)));
// Scale: base places = current places + waitlist (spec §4.6).
const scaleWaitlist = scaleObs.snap.pilotEnd!.signals.waitlist;
write("cost.scale", C.CostResult, costToContinue({ ...scaleObs.assumptions, places: scaleObs.assumptions.places + (C.isSuppressed(scaleWaitlist) ? 0 : scaleWaitlist) }, weeklyHours(scaleObs.snap)));
// The final UI's starting sliders, through the same function as /api/preview.
write("preview", C.PreviewResult, previewEstimate(PREVIEW_START));

// ---------- misc ----------
