// Generates css/tokens.css, css/tailwind.css, src/tokens.js and themes/*.css from tokens/tokens.json
// and themes/*.json, so the JSON stays the single source of truth. Run: npm run build
import { readFileSync, writeFileSync, readdirSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const read = (p) => JSON.parse(readFileSync(join(root, p), "utf8"));
const write = (p, s) => {
  mkdirSync(dirname(join(root, p)), { recursive: true });
  writeFileSync(join(root, p), s);
};
const header = "/* Generated by scripts/build.mjs from tokens/tokens.json. Do not edit by hand. */\n";

const t = read("tokens/tokens.json");
const colors = Object.fromEntries(Object.entries(t.color).map(([k, v]) => [k, v.$value]));
const shapeFills = Object.fromEntries(Object.entries(t["shape-fill"]).map(([k, v]) => [k, v.$value]));
const radius = Object.fromEntries(Object.entries(t.radius).map(([k, v]) => [k, v.$value]));
const space = Object.fromEntries(Object.entries(t.space).map(([k, v]) => [k, v.$value]));

// css/tokens.css: plain CSS custom properties, prefixed --br- so they never collide with an app's own.
const vars = [
  ...Object.entries(colors).map(([k, v]) => `  --br-${k}: ${v};`),
  ...Object.entries(shapeFills).map(([k, v]) => `  --br-shape-${k}: ${v};`),
  ...t.chart.series.$value.map((v, i) => `  --br-chart-${i + 1}: ${v};`),
  `  --br-font: ${t.font.family.$value};`,
  ...Object.entries(t.type).flatMap(([k, v]) => [
    `  --br-type-${k}-size: ${v.fontSize};`,
    `  --br-type-${k}-weight: ${v.fontWeight};`,
    `  --br-type-${k}-leading: ${v.lineHeight};`,
  ]),
  ...Object.entries(radius).map(([k, v]) => `  --br-radius-${k}: ${v};`),
  ...Object.entries(space).map(([k, v]) => `  --br-space-${k}: ${v};`),
  `  --br-target-min: ${t.size["target-min"].$value};`,
  `  --br-input-height: ${t.size["input-height"].$value};`,
  `  --br-focus: ${t.focus.outline.$value};`,
  `  --br-focus-offset: ${t.focus.offset.$value};`,
  // The employer layer defaults to SE Health plum until a theme sets it.
  `  --br-employer-accent: ${colors.plum};`,
  `  --br-employer-accent-text: ${colors.white};`,
  `  --br-employer-tint: ${colors["plum-tint"]};`,
];
write("css/tokens.css", `${header}:root {\n${vars.join("\n")}\n}\n`);

// css/tailwind.css: a Tailwind v4 @theme block (bg-se-red, text-plum, rounded-xl, font-sans ...).
const tw = [
  ...Object.keys(colors).map((k) => `  --color-${k}: var(--br-${k});`),
  ...t.chart.series.$value.map((_, i) => `  --color-chart-${i + 1}: var(--br-chart-${i + 1});`),
  `  --color-employer: var(--br-employer-accent);`,
  `  --color-employer-tint: var(--br-employer-tint);`,
  `  --font-sans: var(--br-font);`,
  ...Object.keys(radius).filter((k) => k !== "full").map((k) => `  --radius-${k}: var(--br-radius-${k});`),
  `  --shadow-*: initial;`,
];
write("css/tailwind.css", `${header}@import "./tokens.css";\n\n@theme {\n${tw.join("\n")}\n}\n`);

// src/tokens.js: the same values for JavaScript (charts, inline styles, Recharts).
const js = {
  colors,
  shapeFills,
  tones: t.tone,
  chart: { series: t.chart.series.$value, bar: t.chart.bar.$value, barCurrent: t.chart["bar-current"].$value, line: t.chart.line.$value, well: t.chart.well.$value },
  font: { family: t.font.family.$value, googleFontsUrl: t.font["google-fonts-url"].$value },
  type: t.type,
  typeFloorPx: 12,
  radius,
  space,
  targetMinPx: 44,
  iconStroke: t.size["icon-stroke"].$value,
  privacy: { minGroupSize: t.privacy["min-group-size"].$value, hiddenText: t.privacy["hidden-text"].$value, tooltip: t.privacy.tooltip.$value },
};
write("src/tokens.js", `// Generated by scripts/build.mjs from tokens/tokens.json. Do not edit by hand.\nexport const tokens = ${JSON.stringify(js, null, 2)};\n`);

// themes/<slug>.css: one employer co-brand layer per JSON file, scoped to [data-employer].
const themes = {};
for (const file of readdirSync(join(root, "themes")).filter((f) => f.endsWith(".json"))) {
  const th = read(`themes/${file}`);
  themes[th.slug] = th;
  write(
    `themes/${th.slug}.css`,
    `${header}/* ${th.name}${th.fictional ? " (fictional)" : ""}: co-brand layer. SE Red stays the only hero colour. */\n` +
      `[data-employer="${th.slug}"] {\n  --br-employer-accent: ${th.accent};\n  --br-employer-accent-text: ${th.accentText};\n  --br-employer-tint: ${th.accentTint};\n}\n`,
  );
}
write("src/themes.js", `// Generated by scripts/build.mjs from themes/*.json. Do not edit by hand.\nexport const themes = ${JSON.stringify(themes, null, 2)};\n`);

console.log(`Built tokens (${Object.keys(colors).length} colours) and ${Object.keys(themes).length} employer theme(s).`);
